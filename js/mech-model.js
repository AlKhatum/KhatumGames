    for (const id in mapCountries) if (mapCountries[id].alliance === b.id) add(id, "map");
    memberIds(b).forEach(id => add(id, "list"));
    for (const id in gmCountries || {}) if (blocLinks(rules, gmCountries[id], id)[b.id] === "gm") add(id, "gm");
